<p>Certain visitors to GK’s websites choose to interact with GK in ways that require GK to gather personally-identifying information. The amount and type of information that GK gathers depends on the nature of the interaction. For example, we ask visitors who comment on our blog to provide a username and email address. Those who wish to receive GK, we collect their emails. In each case, GK collects such information only insofar as is necessary or appropriate to fulfill the purpose of the visitor’s interaction with GK. GK does not disclose personally-identifying information other than as described below. And visitors can always refuse to supply personally-identifying information, with the caveat that it may prevent them from engaging in certain website-related activities.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>Aggregated Statistics</p>
