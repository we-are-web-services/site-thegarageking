<p>Protection of Certain Personally-Identifying Information</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>GK discloses potentially personally-identifying and personally-identifying information only to those of its employees, contractors and affiliated organizations that (i) need to know that information in order to process it on GK’s behalf or to provide services available at GK’s websites, and (ii) that have agreed not to disclose it to others. Some of those employees, contractors and affiliated organizations may be located outside of your home country; by using GK’s website, you consent to the transfer of such information to them. GK will not rent or sell potentially personally-identifying and personally-identifying information to anyone. Other than to its employees, contractors and affiliated organizations, as described above, GK discloses potentially personally-identifying and personally-identifying information only in response to a subpoena, court order or other governmental request, or when GK believes in good faith that disclosure is reasonably necessary to protect the property or rights of GK, third parties or the public at large. If you are a registered user of the GK website and have supplied your email address, GK may occasionally send you an email to tell you about new features, solicit your feedback, or just keep you up to date with what’s going on with GK and our products. We primarily use our various product blogs to communicate this type of information, so we expect to keep this type of email to a minimum. If you send us a request (for example via a support email or via one of our feedback mechanisms), we reserve the right to publish it in order to help us clarify or respond to your request or to help us support other users. GK takes all measures reasonably necessary to protect against the unauthorized access, use, alteration or destruction of potentially personally-identifying and personally-identifying information.</p>
