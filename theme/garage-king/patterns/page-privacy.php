<p>Like most website operators, GK collects non-personally-identifying information of the sort that web browsers and servers typically make available, such as the browser type, language preference, referring site, and the date and time of each visitor request.GK’s purpose in collecting non-personally identifying information is to better understand how GK’s visitors use its website. From time to time, GK may release non-personally-identifying information in the aggregate, e.g., by publishing a report on trends in the usage of its website.</p>
